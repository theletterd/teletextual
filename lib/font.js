// Returns two rows of mosaic segments, one segment per letter so each can be coloured.
// Pixel rows: 1px top margin, 5px glyph = 6px = 2 cell rows.
export function bigRows(text, colours, bg) {
  const rows = [{ s: [{ t: ' ', bg }] }, { s: [{ t: ' ', bg }] }];
  [...text.toUpperCase()].forEach((ch, n) => {
    const g = GLYPHS[ch] ?? GLYPHS[' '];
    const px = ['....', ...g.map((r) => r + '.')]; // 6 rows x 4 cols
    const fg = colours[n % colours.length];
    for (let r = 0; r < 2; r++) {
      const cells = [];
      for (let c = 0; c < 2; c++) {
        let bits = 0;
        for (let y = 0; y < 3; y++) for (let x = 0; x < 2; x++) {
          if (px[r * 3 + y][c * 2 + x] === '#') bits |= 1 << (y * 2 + x);
        }
        cells.push(bits);
      }
      rows[r].s.push({ m: cells, fg, bg });
    }
  });
  return rows;
}
